import os
import glob
import argparse
import numpy as np
import random
from tqdm import tqdm


class PureStageBPatchSaver:
    """
    Region-Scan + Jitter Positive Patch Sampler (Time,Trace)

    Region-scanning positive-patch sampler.

    The sampler identifies target-bearing trace segments, scans each segment
    laterally with jitter, and requires every saved patch to contain positive AT
    samples. All sample-aligned 2-D attributes in the input NPZ are cropped and
    saved together with the mask and available metadata. Attributes that are not
    present in the line-level input are not generated by this step.
    """

    def __init__(self, npz_dir, output_root, seed=42):
        self.npz_dir = npz_dir
        self.output_root = output_root
        random.seed(seed)
        np.random.seed(seed)

        # -----------------------------
        # Core
        # -----------------------------
        self.PATCH = 256
        self.IGNORE_VAL = 255
        self.MIN_VALID_RATIO = 0.5

        self.DEDUP = True
        self.SAVE_META = True

        # -----------------------------
        # Region-scanning and jitter parameters.
        # -----------------------------
        self.GAP_X = 80
        self.SCAN_STRIDE_X = 100
        self.SHAKE_T = 80
        self.SHAKE_X = 40
        self.JITTER_PER_STEP = 4
        self.USE_TOP_MED_BOT = True
        self.MAX_SAVE_PER_LINE = 4000

        # Optional: keep patches close to AT (AT center near patch center)
        self.CENTER_TOL_T = 140
        self.CENTER_TOL_X = 110
        self.ENABLE_CENTER_CONSTRAINT = True

        # -----------------------------
        # Save every sample-aligned attribute channel from the input NPZ.
        # -----------------------------
        self.SAVE_ALL_2D_CHANNELS = True

        # Output
        self.dir_pos = os.path.join(output_root, "positive")
        self._reset_dir(self.dir_pos)

    def _reset_dir(self, path):
        # Keep existing research outputs intact; use a fresh output directory.
        if os.path.lexists(path) and (
            os.path.islink(path) or not os.path.isdir(path) or os.listdir(path)
        ):
            raise FileExistsError(f"Refusing to replace existing output: {path}. Use a new output directory.")
        os.makedirs(path, exist_ok=True)

    # ---------------- Load Data (No transpose) ----------------
    def _load_arrays(self, fp):
        """
        Load all 2D (H,W) channels from NPZ + mask.
        Returns:
            arrs: dict of arrays, including at least "mask" and "raw".
                  Will also store arrs["_axis_val"] if axis exists.
        """
        try:
            data = np.load(fp, allow_pickle=True)
        except Exception as e:
            print(f"Error loading {fp}: {e}")
            return None

        keys = list(data.files)

        def find_key(candidates):
            for cand in candidates:
                for k in keys:
                    if cand.lower() in k.lower():
                        return k
            return None

        # ---- mask must exist ----
        msk_k = find_key(["mask", "msk", "label", "gt"])
        if msk_k is None:
            return None

        mask = data[msk_k]
        if isinstance(mask, np.ndarray) and mask.ndim == 3:
            mask = np.squeeze(mask)
        mask = mask.astype(np.int16)

        if mask.ndim != 2:
            raise ValueError(f"{os.path.basename(fp)}: mask must be 2D, got {mask.shape}")

        H, W = mask.shape
        arrs = {"mask": mask}

        # ---- raw must exist (guardrail) ----
        raw_k = find_key(["raw", "img", "data", "seis", "amp", "amplitude"])
        if raw_k is None:
            raise ValueError(f"{os.path.basename(fp)}: raw not found in keys={keys}")

        # ---- inherit axis if exists ----
        axis_val = None
        if "axis" in keys:
            axis_val = data["axis"]  # bytes or str/ndarray
        elif "axis_tag" in keys:
            axis_val = data["axis_tag"]

        # Option A: save all 2D channels with same shape
        if self.SAVE_ALL_2D_CHANNELS:
            for k in keys:
                if k == msk_k:
                    continue
                x = data[k]

                # squeeze possible (H,W,1)
                if isinstance(x, np.ndarray) and x.ndim == 3:
                    x = np.squeeze(x)

                if not isinstance(x, np.ndarray):
                    continue
                if x.ndim != 2:
                    continue
                if x.shape != (H, W):
                    continue

                # Output dtype policy.
                # - mask already handled as int16
                # - raw float32
                # - all other 2D channels force float32 (avoid int16 "attribute" mixing)
                if k == raw_k:
                    arrs["raw"] = x.astype(np.float32)
                else:
                    arrs[k] = x.astype(np.float32)
        else:
            # Option B: only raw/env + mask (legacy)
            arrs["raw"] = np.squeeze(data[raw_k]).astype(np.float32)
            env_k = find_key(["env", "envelop"])
            if env_k is not None:
                env = data[env_k]
                if isinstance(env, np.ndarray) and env.ndim == 3:
                    env = np.squeeze(env)
                if isinstance(env, np.ndarray) and env.ndim == 2 and env.shape == (H, W):
                    arrs["env"] = env.astype(np.float32)

        # safety: ensure raw exists and aligns
        if "raw" not in arrs:
            raise ValueError(f"{os.path.basename(fp)}: failed to load raw into arrs")

        for name, x in arrs.items():
            if name == "_axis_val":
                continue
            if not isinstance(x, np.ndarray) or x.ndim != 2 or x.shape != (H, W):
                raise ValueError(
                    f"{os.path.basename(fp)}: invalid array '{name}' shape={getattr(x, 'shape', None)}; "
                    f"expected (H,W)={(H, W)}"
                )

        if axis_val is not None:
            arrs["_axis_val"] = axis_val

        return arrs

    # ---------------- Helpers ----------------
    def _valid_ratio(self, m):
        return float((m != self.IGNORE_VAL).mean())

    def _pos_pixels(self, m):
        valid = (m != self.IGNORE_VAL)
        return int(((m == 1) & valid).sum())

    def _save_patch(self, arrs: dict, save_path: str, meta: dict):
        """
        Save cropped patch for all channels in arrs (including mask).
        Inherit axis if present; otherwise default "Time,Trace".
        """
        P = self.PATCH
        top, left = meta["top"], meta["left"]

        save_dict = {}
        for name, x in arrs.items():
            if name == "_axis_val":
                continue
            save_dict[name] = x[top:top + P, left:left + P]

        if self.SAVE_META:
            save_dict["meta"] = np.array([meta], dtype=object)

            axis_val = arrs.get("_axis_val", None)
            if axis_val is None:
                save_dict["axis"] = np.bytes_(b"Time,Trace")
            else:
                save_dict["axis"] = axis_val

        np.savez_compressed(save_path, **save_dict)

    def _clamp_top_left(self, top, left, H, W, P):
        top = max(0, min(H - P, int(top)))
        left = max(0, min(W - P, int(left)))
        return top, left

    def _split_by_gaps(self, cols, gap_x: int):
        cols = np.asarray(cols, dtype=np.int32)
        cols = np.sort(cols)
        if len(cols) == 0:
            return []
        groups = []
        start = 0
        for i in range(1, len(cols)):
            if cols[i] - cols[i - 1] > gap_x:
                groups.append(cols[start:i])
                start = i
        groups.append(cols[start:])
        return groups

    def _at_center_ok(self, p_pos: np.ndarray, tol_t: int, tol_x: int):
        ys, xs = np.where(p_pos)
        if len(ys) == 0:
            return False
        cy = float(ys.mean())
        cx = float(xs.mean())
        P = p_pos.shape[0]
        return (abs(cy - P / 2) <= tol_t) and (abs(cx - P / 2) <= tol_x)

    # ---------------- Main logic ----------------
    def _process_one_line(self, fp):
        fname_no_ext = os.path.basename(fp).replace(".npz", "")

        arrs = self._load_arrays(fp)
        if arrs is None:
            return 0, 0, 0.0

        mask = arrs["mask"]
        H, W = mask.shape
        P = self.PATCH
        if H < P or W < P:
            return 0, 0, 0.0

        valid = (mask != self.IGNORE_VAL)
        pos = (mask == 1) & valid
        n_pos_total = int(pos.sum())
        if n_pos_total == 0:
            return 0, 0, 1.0

        cols_has = np.where(np.any(pos, axis=0))[0]
        col_groups = self._split_by_gaps(cols_has, self.GAP_X)
        if not col_groups:
            return 0, n_pos_total, 0.0

        used_coords = set()
        saved_count = 0
        covered_pos = np.zeros_like(pos, dtype=bool)

        for region_id, cols in enumerate(col_groups):
            if saved_count >= self.MAX_SAVE_PER_LINE:
                break

            start_col = int(cols[0])
            end_col = int(cols[-1])
            scan_cols = list(range(start_col, end_col + 1, self.SCAN_STRIDE_X))

            for step_i, cc in enumerate(scan_cols):
                if saved_count >= self.MAX_SAVE_PER_LINE:
                    break

                ys = np.where(pos[:, cc])[0]
                if len(ys) == 0:
                    continue

                y_top = int(ys.min())
                y_bot = int(ys.max())
                y_med = int(np.median(ys))

                anchors = [(y_med, cc, "med")]
                if self.USE_TOP_MED_BOT:
                    anchors = [(y_top, cc, "top"), (y_med, cc, "med"), (y_bot, cc, "bot")]

                for (rr, cc2, a_tag) in anchors:
                    for j in range(self.JITTER_PER_STEP):
                        shake_r = np.random.randint(-self.SHAKE_T, self.SHAKE_T + 1)
                        shake_c = np.random.randint(-self.SHAKE_X, self.SHAKE_X + 1)

                        base_top = rr - P // 2
                        base_left = cc2 - P // 2

                        top = base_top + shake_r
                        left = base_left + shake_c
                        top, left = self._clamp_top_left(top, left, H, W, P)

                        key = (top, left)
                        if self.DEDUP and key in used_coords:
                            continue

                        p_msk = mask[top:top + P, left:left + P]
                        if self._valid_ratio(p_msk) < self.MIN_VALID_RATIO:
                            continue

                        pospix = self._pos_pixels(p_msk)
                        if pospix <= 0:
                            continue

                        p_pos = pos[top:top + P, left:left + P]
                        if self.ENABLE_CENTER_CONSTRAINT:
                            if not self._at_center_ok(p_pos, self.CENTER_TOL_T, self.CENTER_TOL_X):
                                continue

                        new_cover = int((p_pos & (~covered_pos[top:top + P, left:left + P])).sum())
                        if new_cover < 2 and a_tag == "med":
                            continue

                        save_name = (
                            f"{fname_no_ext}_Unified_B_region{region_id}_step{step_i}_"
                            f"{a_tag}_r{top}_c{left}_j{j}.npz"
                        )
                        meta = {
                            "orig_file": fname_no_ext,
                            "stage": "B_RegionScan_Jitter_AllAttrs",
                            "region_id": int(region_id),
                            "scan_step": int(step_i),
                            "scan_col": int(cc),
                            "anchor": (int(rr), int(cc2)),
                            "anchor_tag": a_tag,
                            "top": int(top),
                            "left": int(left),
                            "pos_pixels": int(pospix),
                            "shake_t": int(self.SHAKE_T),
                            "shake_x": int(self.SHAKE_X),
                            "scan_stride_x": int(self.SCAN_STRIDE_X),
                            "gap_x": int(self.GAP_X),
                            "center_tol_t": int(self.CENTER_TOL_T),
                            "center_tol_x": int(self.CENTER_TOL_X),
                            "new_cover_pos": int(new_cover),
                            "saved_keys": sorted([k for k in arrs.keys() if k != "_axis_val"]),
                        }

                        self._save_patch(arrs, os.path.join(self.dir_pos, save_name), meta)

                        used_coords.add(key)
                        covered_pos[top:top + P, left:left + P] |= p_pos
                        saved_count += 1

                        if saved_count >= self.MAX_SAVE_PER_LINE:
                            break

        uncovered_final = int((pos & (~covered_pos)).sum())
        coverage = 1.0 - (uncovered_final / max(1, n_pos_total))
        return saved_count, n_pos_total, coverage

    def run(self):
        files = sorted(glob.glob(os.path.join(self.npz_dir, "*.npz")))
        if not files:
            print(f"No NPZ files found in: {self.npz_dir}")
            return

        print(f"Start region-scan positive sampling ({len(files)} lines)...")
        print(f"   Assumption: Data is (Time, Trace)")
        print(f"   PATCH={self.PATCH} | SCAN_STRIDE_X={self.SCAN_STRIDE_X} | GAP_X={self.GAP_X}")
        print(f"   SHAKE_T/X={self.SHAKE_T}/{self.SHAKE_X} | JITTER_PER_STEP={self.JITTER_PER_STEP}")
        print(f"   CENTER_CONSTRAINT={self.ENABLE_CENTER_CONSTRAINT} tolT/tolX={self.CENTER_TOL_T}/{self.CENTER_TOL_X}")
        print(f"   SAVE_ALL_2D_CHANNELS={self.SAVE_ALL_2D_CHANNELS}")

        total_saved = 0
        for fp in tqdm(files, desc="Lines"):
            try:
                saved, npos, cov = self._process_one_line(fp)
                total_saved += saved
                if npos > 100 and cov < 0.95:
                    tqdm.write(f"  [Low positive coverage] {os.path.basename(fp)}: {cov * 100:.1f}%")
            except Exception as e:
                print(f"\nError: {os.path.basename(fp)} - {e}")

        print(f"\nDone. Saved {total_saved} patches to {self.dir_pos}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Extract positive training patches from attributed line-level NPZ files."
    )
    parser.add_argument("--input-dir", required=True, help="Directory containing attributed line NPZ files")
    parser.add_argument("--output-dir", required=True, help="Directory for positive patches")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    saver = PureStageBPatchSaver(args.input_dir, args.output_dir, seed=args.seed)
    saver.run()
